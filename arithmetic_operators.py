a = 15
b = 4

# Addition +
print("Addition:", a + b)

# Subtraction (-)
print("Subtraction:", a - b)

# Multiplication (*)
print("Multiplication:", a * b)

# True Division (float result)
print("Division:", a / b)

# Floor Division(integer floor) //
print("Floor Division:", a // b)

# Modulus (remainder) %
print("Modulus:", a % b)

# Exponentiation (power) **
print("Exponentation:", a ** b)